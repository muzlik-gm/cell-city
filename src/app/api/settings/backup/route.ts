import { NextResponse } from "next/server";
import { db } from "@/lib/db";

// GET /api/settings/backup — full JSON dump of all key tables for export.
// Excludes passwordHash on users. Suitable for client-side JSON download.
export async function GET() {
  const [
    settings,
    brands,
    models,
    partTypes,
    warehouses,
    shelves,
    suppliers,
    customers,
    users,
    products,
    sales,
    saleItems,
    purchases,
    purchaseItems,
    repairJobs,
    repairJobParts,
    damagedInventory,
    inventoryMovements,
    priceHistory,
    compatibility,
  ] = await Promise.all([
    db.setting.findMany(),
    db.brand.findMany(),
    db.phoneModel.findMany(),
    db.partType.findMany(),
    db.warehouse.findMany(),
    db.shelf.findMany(),
    db.supplier.findMany(),
    db.customer.findMany(),
    db.user.findMany({ select: { id: true, email: true, name: true, role: true, phone: true, active: true, avatarUrl: true, lastLogin: true, createdAt: true, updatedAt: true } }),
    db.product.findMany(),
    db.sale.findMany(),
    db.saleItem.findMany(),
    db.purchase.findMany(),
    db.purchaseItem.findMany(),
    db.repairJob.findMany(),
    db.repairJobPart.findMany(),
    db.damagedInventory.findMany(),
    db.inventoryMovement.findMany(),
    db.priceHistory.findMany(),
    db.modelCompatibility.findMany(),
  ]);

  return NextResponse.json({
    exportedAt: new Date().toISOString(),
    version: 1,
    counts: {
      settings: settings.length,
      brands: brands.length,
      models: models.length,
      partTypes: partTypes.length,
      warehouses: warehouses.length,
      shelves: shelves.length,
      suppliers: suppliers.length,
      customers: customers.length,
      users: users.length,
      products: products.length,
      sales: sales.length,
      saleItems: saleItems.length,
      purchases: purchases.length,
      purchaseItems: purchaseItems.length,
      repairJobs: repairJobs.length,
      repairJobParts: repairJobParts.length,
      damagedInventory: damagedInventory.length,
      inventoryMovements: inventoryMovements.length,
      priceHistory: priceHistory.length,
      compatibility: compatibility.length,
    },
    data: {
      settings,
      brands,
      models,
      partTypes,
      warehouses,
      shelves,
      suppliers,
      customers,
      users,
      products,
      sales,
      saleItems,
      purchases,
      purchaseItems,
      repairJobs,
      repairJobParts,
      damagedInventory,
      inventoryMovements,
      priceHistory,
      compatibility,
    },
  });
}
